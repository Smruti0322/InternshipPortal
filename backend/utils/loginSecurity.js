const crypto = require("crypto");
const db = require("../config/db");

// =========================================================
// CHECK TRUSTED DEVICE
// =========================================================

const checkTrustedDevice = async (
    userId,
    loginEnvironment
) => {
    try {
        const [trustedDevices] = await db.query(
            `SELECT
                id,
                browser_name,
                browser_version,
                operating_system,
                os_version,
                device_type,
                device_model,
                last_ip_address,
                is_active
             FROM trusted_devices
             WHERE user_id = ?
               AND device_identifier = ?
               AND is_active = 1
             LIMIT 1`,
            [
                userId,
                loginEnvironment.deviceIdentifier
            ]
        );

        // No trusted device found
        if (trustedDevices.length === 0) {
            return {
                isNewDevice: true,
                isNewBrowser: true,
                isNewIp: true,
                trustedDevice: null
            };
        }

        const trustedDevice =
            trustedDevices[0];

        const isNewBrowser =
            trustedDevice.browser_name !==
            loginEnvironment.browserName;

        const isNewIp =
            Boolean(
                trustedDevice.last_ip_address &&
                loginEnvironment.ipAddress &&
                trustedDevice.last_ip_address !==
                loginEnvironment.ipAddress
            );

        return {
            isNewDevice: false,
            isNewBrowser,
            isNewIp,
            trustedDevice
        };

    } catch (error) {

        console.error(
            "Trusted device check error:",
            error
        );

        // Fail safely.
        // A database error should not silently
        // mark a device as trusted.
        return {
            isNewDevice: true,
            isNewBrowser: true,
            isNewIp: true,
            trustedDevice: null,
            error: true
        };
    }
};


// =========================================================
// SAVE LOGIN HISTORY
// =========================================================

const saveLoginHistory = async ({
    userId,
    loginEnvironment,
    loginStatus,
    failureReason = null,
    otpRequired = 0,
    otpVerified = 0,
    isNewBrowser = 0,
    isNewDevice = 0,
    isNewIp = 0
}) => {

    const [result] = await db.query(
        `INSERT INTO login_history (
            user_id,
            browser_name,
            browser_version,
            operating_system,
            os_version,
            device_type,
            device_model,
            ip_address,
            login_date_time,
            login_status,
            failure_reason,
            otp_required,
            otp_verified,
            is_new_browser,
            is_new_device,
            is_new_ip
        )
        VALUES (
            ?, ?, ?, ?, ?, ?, ?, ?, NOW(), ?, ?, ?, ?, ?, ?, ?
        )`,
        [
            userId,

            loginEnvironment.browserName,
            loginEnvironment.browserVersion,

            loginEnvironment.operatingSystem,
            loginEnvironment.osVersion,

            loginEnvironment.deviceType,
            loginEnvironment.deviceModel,

            loginEnvironment.ipAddress,

            loginStatus,
            failureReason,

            otpRequired,
            otpVerified,

            isNewBrowser,
            isNewDevice,
            isNewIp
        ]
    );

    return result.insertId;
};


// =========================================================
// CREATE DEVICE IDENTIFIER
// =========================================================
// Device identifier is already generated by
// loginEnvironment.js.
// This helper is kept here for future security upgrades.
// =========================================================

const hashValue = (value) => {
    return crypto
        .createHash("sha256")
        .update(String(value))
        .digest("hex");
};


module.exports = {
    checkTrustedDevice,
    saveLoginHistory,
    hashValue
};